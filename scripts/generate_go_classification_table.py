#!/usr/bin/env python3
"""Generate the Go package's fixed irreducible-classification lookup table."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "examples"))

from irreducible_wait_classification_table import (  # noqa: E402
    CLASSIFICATION_CODE_LISTS,
    CLASSIFICATION_ID_OFFSETS,
)


EXPECTED_COUNTS = {1: 1, 4: 11, 7: 49, 10: 199, 13: 708}


def main() -> None:
    entries: list[tuple[str, int]] = []
    for tile_count, expected_count in EXPECTED_COUNTS.items():
        codes_list = CLASSIFICATION_CODE_LISTS[tile_count]
        if len(codes_list) != expected_count:
            raise ValueError(f"{tile_count}-tile table has {len(codes_list)} rows")
        for local_id, codes in enumerate(codes_list):
            if tuple(sorted(codes)) != codes:
                raise ValueError(f"unsorted code list for {tile_count} tiles: {codes}")
            code_key = ",".join(map(str, codes))
            entries.append(
                (f"{tile_count}|{code_key}", CLASSIFICATION_ID_OFFSETS[tile_count] + local_id)
            )

    if len({key for key, _ in entries}) != len(entries):
        raise ValueError("classification table contains duplicate keys")
    if {classification_id for _, classification_id in entries} != set(range(968)):
        raise ValueError("classification IDs must cover 0 through 967 exactly once")

    lines = [
        "// Code generated by scripts/generate_go_classification_table.py; DO NOT EDIT.",
        "",
        "package mahjong",
        "",
        "var irreducibleClassificationIDs = map[string]int{",
    ]
    lines.extend(f'\t"{key}": {classification_id},' for key, classification_id in entries)
    lines.extend(["}", ""])
    (ROOT / "mahjong" / "classification_table.go").write_text(
        "\n".join(lines), encoding="utf-8"
    )


if __name__ == "__main__":
    main()
