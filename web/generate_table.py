"""Generate web/classification-table.js from the Python classification table."""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "examples"))

from irreducible_wait_classification_table import (  # noqa: E402
    CLASSIFICATION_CODE_LISTS,
    CLASSIFICATION_ID_OFFSETS,
)

table = {
    "idOffsets": {str(k): v for k, v in CLASSIFICATION_ID_OFFSETS.items()},
    "codeLists": {str(k): [list(c) for c in v] for k, v in CLASSIFICATION_CODE_LISTS.items()},
}
body = json.dumps(table, separators=(",", ":"))
(HERE / "classification-table.js").write_text(
    "// Generated by web/generate_table.py. Do not edit.\n"
    "(function (root) {\n"
    f"  const table = {body};\n"
    '  if (typeof module === "object" && module.exports) module.exports = table;\n'
    "  else root.WaitClassificationTable = table;\n"
    '})(typeof self !== "undefined" ? self : this);\n',
    encoding="utf-8",
)
